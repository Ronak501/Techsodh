-- Phase 1 + Phase 2 foundation
-- 1) Persistent distributed rate limiting table + atomic RPC function
-- 2) Research report persistence table for history/detail/export flows

create extension if not exists pgcrypto;

create table if not exists public.api_rate_limits (
  id bigint generated by default as identity primary key,
  key text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  ip text,
  scope text not null,
  window_start timestamptz not null,
  window_ms integer not null,
  count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint api_rate_limits_key_window_unique unique (key, window_start)
);

create index if not exists api_rate_limits_user_scope_idx
  on public.api_rate_limits (user_id, scope, window_start desc);

alter table public.api_rate_limits enable row level security;

drop policy if exists "Users can read own rate limits" on public.api_rate_limits;
create policy "Users can read own rate limits"
on public.api_rate_limits for select
using (auth.uid() = user_id);

drop policy if exists "Users can insert own rate limits" on public.api_rate_limits;
create policy "Users can insert own rate limits"
on public.api_rate_limits for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can update own rate limits" on public.api_rate_limits;
create policy "Users can update own rate limits"
on public.api_rate_limits for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create or replace function public.consume_rate_limit(
  p_key text,
  p_user_id uuid,
  p_ip text,
  p_scope text,
  p_window_start timestamptz,
  p_window_ms integer,
  p_limit integer
)
returns table (allowed boolean, current_count integer, retry_after_seconds integer)
language plpgsql
security invoker
as $$
declare
  v_count integer;
  v_retry_seconds integer;
begin
  insert into public.api_rate_limits (key, user_id, ip, scope, window_start, window_ms, count)
  values (p_key, p_user_id, p_ip, p_scope, p_window_start, p_window_ms, 1)
  on conflict (key, window_start)
  do update set
    count = public.api_rate_limits.count + 1,
    updated_at = now()
  returning count into v_count;

  if v_count <= p_limit then
    return query select true, v_count, 0;
  end if;

  v_retry_seconds := greatest(
    1,
    ceil(extract(epoch from ((p_window_start + (p_window_ms || ' milliseconds')::interval) - now())))::integer
  );

  return query select false, v_count, v_retry_seconds;
end;
$$;

grant execute on function public.consume_rate_limit(text, uuid, text, text, timestamptz, integer, integer) to authenticated;

create table if not exists public.research_reports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  query text not null,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed', 'failed')),
  outline jsonb,
  report jsonb,
  error_message text,
  source_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists research_reports_user_created_idx
  on public.research_reports (user_id, created_at desc);

alter table public.research_reports enable row level security;

drop policy if exists "Users can read own reports" on public.research_reports;
create policy "Users can read own reports"
on public.research_reports for select
using (auth.uid() = user_id);

drop policy if exists "Users can insert own reports" on public.research_reports;
create policy "Users can insert own reports"
on public.research_reports for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can update own reports" on public.research_reports;
create policy "Users can update own reports"
on public.research_reports for update
